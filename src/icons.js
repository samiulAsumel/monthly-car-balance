/**
 * Returns an inline <svg> string for the named icon.
 * @param {string} name key into ICONS
 * @param {number} size square size in px (default 16)
 * @param {string} cls extra class names appended to "ic"
 */
function icon(name, size, cls) {
  size = size || 16;
  cls = cls ? "ic " + cls : "ic";
  const body = ICONS[name];
  if (!body) return "";
  return (
    '<svg class="' +
    cls +
    '" width="' +
    size +
    '" height="' +
    size +
    '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ' +
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' +
    body +
    "</svg>"
  );
}

// Replaces every static `<span data-icon="name" [data-icon-size="n"]>` placeholder
// under `root` with its rendered SVG. Called once for the static index.html markup;
// anything app.js generates dynamically calls icon() directly in its template string.
function hydrateIcons(root) {
  (root || document).querySelectorAll("[data-icon]").forEach((el) => {
    const name = el.getAttribute("data-icon");
    const size = parseInt(el.getAttribute("data-icon-size"), 10) || 16;
    el.innerHTML = icon(name, size);
    el.removeAttribute("data-icon");
  });
}

